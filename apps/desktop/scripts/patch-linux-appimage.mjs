import {
	chmodSync,
	copyFileSync,
	existsSync,
	mkdtempSync,
	readdirSync,
	rmSync,
	statSync,
	writeFileSync
} from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';

const bundleDirectory = resolve(
	process.env.LINUX_APPIMAGE_DIR ?? 'apps/desktop/src-tauri/target/release/bundle/appimage'
);
const appImageCandidate =
	process.env.LINUX_APPIMAGE ??
	readdirSync(bundleDirectory)
		.filter((file) => file.endsWith('.AppImage'))
		.map((file) => join(bundleDirectory, file))
		.find((file) => statSync(file).isFile());
const appImagePath = appImageCandidate ? resolve(appImageCandidate) : '';
const appImageTool = process.env.APPIMAGETOOL ?? 'appimagetool';

if (!appImagePath || !existsSync(appImagePath)) {
	throw new Error(`Linux AppImage not found in ${bundleDirectory}`);
}

function run(command, args, options = {}) {
	const result = spawnSync(command, args, {
		cwd: options.cwd,
		env: { ...process.env, ...options.env },
		stdio: 'inherit'
	});

	if (result.error) throw result.error;
	if (result.status !== 0) {
		throw new Error(`${command} ${args.join(' ')} exited with status ${result.status}`);
	}
}

function removeWaylandLibraries(directory, removed = []) {
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		const path = join(directory, entry.name);
		if (entry.isDirectory()) {
			removeWaylandLibraries(path, removed);
			continue;
		}
		if (!entry.name.startsWith('libwayland-')) continue;
		rmSync(path, { force: true });
		removed.push(path);
	}
	return removed;
}

function patchAppRun(appDir) {
	const appRunPath = join(appDir, 'AppRun');
	const appRunWrappedPath = join(appDir, 'AppRun.wrapped');
	const executablePath = join(appDir, 'usr/bin/openbible-desktop');
	if (!existsSync(appRunPath) || !existsSync(appRunWrappedPath) || !existsSync(executablePath)) {
		return false;
	}

	const appRun = `#!/usr/bin/env bash
set -euo pipefail

appdir="$(cd -- "$(dirname -- "\${BASH_SOURCE[0]}")" && pwd)"
export APPDIR="\${APPDIR:-$appdir}"

if [[ -f "$appdir/apprun-hooks/linuxdeploy-plugin-gtk.sh" ]]; then
  # Keep the GTK setup generated by linuxdeploy, but do not invoke AppRun.wrapped:
  # it reintroduces GST_PLUGIN_SYSTEM_PATH pointing at a non-existent bundle path.
  source "$appdir/apprun-hooks/linuxdeploy-plugin-gtk.sh"
fi

unset GST_PLUGIN_PATH GST_PLUGIN_SYSTEM_PATH GST_PLUGIN_SYSTEM_PATH_1_0
export PATH="$appdir/usr/bin:$PATH"
if [[ -n "\${LD_LIBRARY_PATH:-}" ]]; then
  export LD_LIBRARY_PATH="$appdir/usr/lib:$appdir/usr/lib/x86_64-linux-gnu:$appdir/usr/lib64:$LD_LIBRARY_PATH"
else
  export LD_LIBRARY_PATH="$appdir/usr/lib:$appdir/usr/lib/x86_64-linux-gnu:$appdir/usr/lib64"
fi

cd "$appdir/usr"
exec "$appdir/usr/bin/openbible-desktop" "$@"
`;

	writeFileSync(appRunPath, appRun);
	chmodSync(appRunPath, 0o755);
	return true;
}

const temporaryDirectory = mkdtempSync(join(tmpdir(), 'openbible-appimage-'));
try {
	chmodSync(appImagePath, 0o755);
	run(appImagePath, ['--appimage-extract'], {
		cwd: temporaryDirectory,
		env: { APPIMAGE_EXTRACT_AND_RUN: '1' }
	});

	const appDir = join(temporaryDirectory, 'squashfs-root');
	if (!existsSync(appDir)) throw new Error(`AppImage extraction did not create ${appDir}`);

	const removedLibraries = removeWaylandLibraries(join(appDir, 'usr'));
	const appRunPatched = patchAppRun(appDir);
	const outputPath = join(temporaryDirectory, `patched-${basename(appImagePath)}`);

	console.log(`Removed ${removedLibraries.length} bundled Wayland libraries`);
	if (!appRunPatched)
		console.log('AppRun wrapper not replaced (layout does not use linuxdeploy AppRun.wrapped)');

	run(appImageTool, [appDir, outputPath], { env: { APPIMAGE_EXTRACT_AND_RUN: '1' } });
	copyFileSync(outputPath, appImagePath);
	chmodSync(appImagePath, 0o755);
	rmSync(`${appImagePath}.sig`, { force: true });
	console.log(`Patched AppImage: ${appImagePath}`);
} finally {
	rmSync(temporaryDirectory, { recursive: true, force: true });
}
